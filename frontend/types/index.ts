/**
 * Response shape from the backend GET /health endpoint.
 */
export interface HealthCheckResponse {
  /** Overall service status. */
  status: 'ok' | 'degraded' | 'down';
  /** ISO-8601 datetime of this response. */
  timestamp: string;
  /** Semantic version string of the backend service (e.g. "1.0.0"). */
  version: string;
  /** Individual sub-system statuses. */
  services: {
    /** PostgreSQL database connectivity. */
    database: 'ok' | 'error';
    /** MQTT broker connectivity. */
    mqtt: 'ok' | 'error';
    /** Redis/cache connectivity (if applicable). */
    cache?: 'ok' | 'error';
  };
}

// ---------------------------------------------------------------------------
// Socket.IO Event Payload Types
// ---------------------------------------------------------------------------

/**
 * Payload emitted by the server on the `reading:update` Socket.IO event.
 * Contains the most recent readings for both resources in a single push.
 */
export interface ReadingUpdatePayload {
  /** The deviceId that generated these readings. */
  deviceId: string;
  /** Latest water reading, or null if none yet received. */
  water: WaterReading | null;
  /** Latest electricity reading, or null if none yet received. */
  electricity: ElectricityReading | null;
}

/**
 * Payload emitted by the server on the `device:status` Socket.IO event.
 */
export interface DeviceStatusPayload {
  /** The deviceId whose status changed. */
  deviceId: string;
  /** New connectivity status. */
  status: 'online' | 'offline';
  /** ISO-8601 datetime of the status change. */
  timestamp: string;
  /** Wi-Fi RSSI at the time of the event (if applicable). */
  rssi?: number | null;
  /** Free heap at the time of the event (if applicable). */
  freeHeap?: number | null;
}

