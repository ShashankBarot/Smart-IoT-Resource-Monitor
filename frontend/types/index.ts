// ---------------------------------------------------------------------------
// Core Entity Types
// ---------------------------------------------------------------------------

/**
 * Represents a physical IoT device (e.g. an ESP32 node) registered in the system.
 */
export interface Device {
  /** UUID primary key assigned by the database. */
  id: string;
  /** Human-readable device identifier sent in every MQTT/HTTP payload (e.g. "esp32-01"). */
  deviceId: string;
  /** Optional friendly name set by the user. */
  name: string | null;
  /** Current connectivity status derived from the last heartbeat timestamp. */
  status: 'online' | 'offline';
  /** ISO-8601 datetime of the last received message from this device. */
  lastSeenAt: string | null;
  /** Wi-Fi RSSI value in dBm (negative integer). Null if never reported. */
  rssi: number | null;
  /** Free heap memory in bytes as reported by the firmware. */
  freeHeap: number | null;
  /** ISO-8601 datetime when this device was first registered. */
  createdAt: string;
  /** ISO-8601 datetime of the last record update. */
  updatedAt: string;
}

/**
 * A single water flow/volume reading captured by the flow sensor on the device.
 */
export interface WaterReading {
  /** UUID primary key. */
  id: string;
  /** Foreign key linking to the originating device's deviceId field. */
  deviceId: string;
  /** Instantaneous flow rate in litres per minute. */
  flowRateLpm: number;
  /** Cumulative total litres dispensed since the device last reset its counter. */
  totalLitres: number;
  /** ISO-8601 datetime when the reading was captured on the device. */
  timestamp: string;
  /** ISO-8601 datetime when the record was persisted in the database. */
  createdAt: string;
}

/**
 * A single electricity reading captured by the PZEM-004T sensor module.
 */
export interface ElectricityReading {
  /** UUID primary key. */
  id: string;
  /** Foreign key linking to the originating device's deviceId field. */
  deviceId: string;
  /** RMS voltage in Volts. */
  voltage: number;
  /** RMS current in Amperes. */
  current: number;
  /** Instantaneous active power in Watts. */
  power: number;
  /** Cumulative energy consumption in kilowatt-hours since last reset. */
  energyKwh: number;
  /** ISO-8601 datetime when the reading was captured on the device. */
  timestamp: string;
  /** ISO-8601 datetime when the record was persisted in the database. */
  createdAt: string;
}

/**
 * An anomaly event generated by the backend anomaly-detection engine.
 */
export interface Anomaly {
  /** UUID primary key. */
  id: string;
  /** Foreign key referencing the device that produced the anomalous reading. */
  deviceId: string;
  /** Which monitored resource triggered the anomaly. */
  resourceType: 'water' | 'electricity';
  /** Classification of how serious the anomaly is. */
  severity: 'low' | 'medium' | 'high';
  /** Human-readable description of what was detected (e.g. "Flow rate 3× above baseline"). */
  message: string;
  /** The actual sensor value that triggered the anomaly. */
  actualValue: number;
  /** The rolling baseline value used for comparison. */
  baselineValue: number;
  /** The deviation threshold that was crossed to generate this anomaly. */
  threshold: number;
  /** ISO-8601 datetime when this anomaly was marked resolved. Null if still active. */
  resolvedAt: string | null;
  /** ISO-8601 datetime when the anomalous reading was captured. */
  timestamp: string;
  /** ISO-8601 datetime when this anomaly record was created in the database. */
  createdAt: string;
}

