/**
 * A single [x, y] data-point used by Recharts or any charting library.
 */
export interface ChartDataPoint {
  /** X-axis label — typically a formatted time string (e.g. "14:30") or date ("Mon"). */
  label: string;
  /** Primary numeric value plotted on the Y axis. */
  value: number;
  /** Optional secondary value (e.g. for multi-line charts). */
  value2?: number;
  /** Raw ISO-8601 timestamp for tooltip display. */
  timestamp?: string;
}

/**
 * Preset time-range identifiers used by the history/chart date-range selector.
 */
export type TimeRange = '1h' | '6h' | '24h' | '7d' | '30d' | 'custom';

/**
 * Standardised error object returned when any API call fails.
 */
export interface ApiError {
  /** Short machine-readable error code (e.g. "DEVICE_NOT_FOUND"). */
  code: string;
  /** Human-readable error message suitable for display in a toast. */
  message: string;
  /** HTTP status code of the failed response. */
  status: number;
  /** Optional validation details for 422 errors. */
  details?: Record<string, string[]>;
}

/**
 * Query parameters accepted by the fetchAnomalies API function.
 */
export interface AnomalyQueryParams {
  /** Filter by deviceId. */
  deviceId?: string;
  /** Filter by resource type. */
  resourceType?: 'water' | 'electricity';
  /** Filter by severity. */
  severity?: 'low' | 'medium' | 'high';
  /** Only return unresolved anomalies when true. */
  unresolvedOnly?: boolean;
  /** Maximum number of results to return. */
  limit?: number;
  /** Zero-based page offset for pagination. */
  offset?: number;
}

/**
 * Query parameters accepted by the history fetch functions.
 */
export interface HistoryQueryParams {
  /** ISO-8601 datetime for the start of the query window. */
  from: string;
  /** ISO-8601 datetime for the end of the query window. */
  to: string;
  /** Maximum number of readings to return (default: 100). */
  limit?: number;
}

/**
 * Generic wrapper for successful paginated API list responses.
 */
export interface PaginatedResponse<T> {
  data: T[];
  total: number;
  limit: number;
  offset: number;
}
