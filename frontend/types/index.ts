/**
 * Summary statistics for water consumption aggregated over the current calendar day.
 */
export interface WaterTodaySummary {
  /** The device this summary belongs to. */
  deviceId: string;
  /** Total litres consumed since 00:00 local time today. */
  totalLitresToday: number;
  /** Average flow rate across all readings taken today, in LPM. */
  avgFlowRateLpm: number;
  /** Peak (maximum) flow rate recorded today, in LPM. */
  peakFlowRateLpm: number;
  /** Total number of individual readings recorded today. */
  readingCount: number;
  /** ISO-8601 start-of-day boundary used for the aggregation. */
  periodStart: string;
  /** ISO-8601 end-of-day boundary (or current time if today is ongoing). */
  periodEnd: string;
}

/**
 * Paginated list of water readings returned by the history endpoint.
 */
export interface WaterHistoryResponse {
  /** Array of reading objects ordered by timestamp descending. */
  data: WaterReading[];
  /** Total number of readings matching the query (before pagination). */
  total: number;
  /** Maximum number of results per page requested. */
  limit: number;
  /** Zero-based page offset. */
  offset: number;
}

/**
 * One day's aggregated water usage record, used to build the weekly summary chart.
 */
export interface WaterDailySummary {
  /** Calendar date string in YYYY-MM-DD format. */
  date: string;
  /** Total litres consumed on this calendar day. */
  totalLitres: number;
  /** Average flow rate across all readings on this day, in LPM. */
  avgFlowRateLpm: number;
  /** Peak flow rate on this day, in LPM. */
  peakFlowRateLpm: number;
  /** Number of individual readings taken on this day. */
  readingCount: number;
}

/**
 * Multi-day water usage summary (e.g. past 7 or 30 days).
 */
export interface WaterSummaryResponse {
  /** The device this summary belongs to. */
  deviceId: string;
  /** Number of days included in this summary. */
  days: number;
  /** Per-day breakdown, one entry per calendar day. */
  dailySummaries: WaterDailySummary[];
  /** Grand total litres across all days in the summary period. */
  grandTotalLitres: number;
  /** Average daily consumption in litres. */
  avgDailyLitres: number;
}

